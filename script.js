// ===============================
// कहानियाँ स्क्रीन पर दिखाना
// ===============================

function render(list = stories) {

  const grid = document.getElementById("storyGrid");

  if (!grid) return;

  grid.innerHTML = list.map((story) => {

    const index = stories.indexOf(story);

    return `
      <article class="card">

        <div class="meta">
          ${escapeHtml(story.cat)} · ${escapeHtml(story.author)}
        </div>

        <h3>
          ${escapeHtml(story.title)}
        </h3>

        <p>
          ${escapeHtml(story.text.substring(0, 140))}...
        </p>

        <button
          class="btn"
          onclick="readStory(${index})">
          पूरी कहानी पढ़ें →
        </button>

      </article>
    `;

  }).join("");
}


// ===============================
// पूरी कहानी खोलना
// ===============================

function readStory(index) {

  const story = stories[index];

  if (!story) {
    alert("कहानी नहीं मिली।");
    return;
  }

  localStorage.setItem(
    "selectedStory",
    JSON.stringify(story)
  );

  window.location.href =
    "/apni-kahaniyan/story.html";
}


// ===============================
// Search
// ===============================

function filterStories() {

  const searchBox =
    document.getElementById("search");

  if (!searchBox) return;

  const q =
    searchBox.value.toLowerCase().trim();

  const filtered =
    stories.filter((story) => {

      return (
        story.title +
        " " +
        story.author +
        " " +
        story.cat +
        " " +
        story.text
      )
      .toLowerCase()
      .includes(q);

    });

  render(filtered);
}


// ===============================
// अपनी कहानी जोड़ना
// ===============================

function addStory() {

  const title =
    document.getElementById("title").value.trim();

  const author =
    document.getElementById("author").value.trim();

  const category =
    document.getElementById("category").value;

  const content =
    document.getElementById("content").value.trim();

  const message =
    document.getElementById("msg");


  if (!title || !author || !content) {

    message.textContent =
      "कृपया सभी जानकारी भरें।";

    return;
  }


  stories.unshift({

    title: title,

    author: author,

    cat: category,

    text: content

  });


  render();


  message.textContent =
    "आपकी कहानी जोड़ दी गई है ❤️";


  document.getElementById("title").value = "";

  document.getElementById("author").value = "";

  document.getElementById("content").value = "";
}


// ===============================
// HTML सुरक्षित रखने के लिए
// ===============================

function escapeHtml(text) {

  const div =
    document.createElement("div");

  div.textContent = text;

  return div.innerHTML;
}


