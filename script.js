let currentCategory = "सभी";


function render(list = stories) {

  const grid = document.getElementById("storyGrid");

  if (!grid) {
    return;
  }

  if (!Array.isArray(list) || list.length === 0) {
    grid.innerHTML = "<p>इस Category में अभी कोई कहानी नहीं है।</p>";
    return;
  }

  grid.innerHTML = list.map(function(story) {

    const index = stories.indexOf(story);

    return `
      <article class="card">

        <div class="meta">
          ${escapeHtml(story.cat)} · ${escapeHtml(story.author)}
        </div>

        <h3>${escapeHtml(story.title)}</h3>

        <p>
          ${escapeHtml(story.text.substring(0, 140))}...
        </p>

        <button
          class="btn"
          type="button"
          onclick="readStory(${index})">
          पूरी कहानी पढ़ें →
        </button>

      </article>
    `;

  }).join("");
}


function filterCategory(category) {

  currentCategory = category;

  const buttons = document.querySelectorAll(".category-btn");

  buttons.forEach(function(button) {

    button.classList.remove("active");

    if (button.textContent.includes(category)) {
      button.classList.add("active");
    }

  });

  const searchBox = document.getElementById("search");

  if (searchBox) {
    searchBox.value = "";
  }

  if (category === "सभी") {
    render(stories);
  } else {

    const filtered = stories.filter(function(story) {
      return story.cat === category;
    });

    render(filtered);
  }
}


function filterStories() {

  const searchBox = document.getElementById("search");

  if (!searchBox) {
    return;
  }

  const q = searchBox.value.toLowerCase().trim();

  let filtered = stories;

  if (currentCategory !== "सभी") {

    filtered = filtered.filter(function(story) {
      return story.cat === currentCategory;
    });

  }

  if (q) {

    filtered = filtered.filter(function(story) {

      const fullText =
        story.title + " " +
        story.author + " " +
        story.cat + " " +
        story.text;

      return fullText.toLowerCase().includes(q);

    });

  }

  render(filtered);
}


function readStory(index) {

  const story = stories[index];

  if (!story) {
    alert("कहानी नहीं मिली।");
    return;
  }

  localStorage.setItem(
    "selectedStory",
    JSON.stringify(story)
  );

  window.location.href = "story.html";
}


function addStory() {

  const titleElement = document.getElementById("title");
  const authorElement = document.getElementById("author");
  const categoryElement = document.getElementById("category");
  const contentElement = document.getElementById("content");
  const message = document.getElementById("msg");

  if (
    !titleElement ||
    !authorElement ||
    !categoryElement ||
    !contentElement ||
    !message
  ) {
    return;
  }

  const title = titleElement.value.trim();
  const author = authorElement.value.trim();
  const category = categoryElement.value;
  const content = contentElement.value.trim();

  if (!title || !author || !content) {
    message.textContent = "कृपया सभी जानकारी भरें।";
    return;
  }

  stories.unshift({
    title: title,
    author: author,
    cat: category,
    text: content
  });

  currentCategory = "सभी";

  render(stories);

  message.textContent = "आपकी कहानी जोड़ दी गई है ❤️";

  titleElement.value = "";
  authorElement.value = "";
  contentElement.value = "";
}


function escapeHtml(text) {

  const div = document.createElement("div");

  div.textContent = String(text);

  return div.innerHTML;
}


document.addEventListener("DOMContentLoaded", function() {
  render(stories);
});
